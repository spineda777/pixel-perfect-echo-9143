const DICTS: Record<Lang, Dict> = { en, es, pt };
export type TKey = keyof Dict;

/** Read a translated database field ({ en, es, pt }) with English fallback. */
export function tr(value: Json | null | undefined, lang: Lang): string {
  if (!value || typeof value !== "object" || Array.isArray(value)) return typeof value === "string" ? value : "";
  const v = value[lang];
  if (typeof v === "string" && v.trim()) return v;
  const fallback = value["en"];
  return typeof fallback === "string" ? fallback : "";
}

interface I18nValue {
  lang: Lang;
  locale: string;
  setLang: (l: Lang) => void;
  t: (key: TKey) => string;
}

const I18nContext = createContext<I18nValue | null>(null);
const STORAGE_KEY = "respawn-lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "es" || stored === "pt") {
      setLangState(stored);
      return;
    }
    const nav = window.navigator.language.toLowerCase();
    if (nav.startsWith("es")) setLangState("es");
    else if (nav.startsWith("pt")) setLangState("pt");
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "pt" ? "pt-BR" : lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      locale: LANGS.find((l) => l.code === lang)?.locale ?? "en-US",
      setLang,
      t: (key) => DICTS[lang][key],
    }),
    [lang, setLang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
